import { chromium } from 'playwright';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { installHelper } from '../scripts/helper.mjs';
const extension=path.resolve('dist');
const context=await chromium.launchPersistentContext('',{channel:'chromium',headless:true,viewport:{width:1200,height:800},args:[`--disable-extensions-except=${extension}`,`--load-extension=${extension}`]});
try {
  const worker=context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
  const id=new URL(worker.url()).host;
  await installHelper(id);
  await worker.evaluate(() => chrome.storage.local.set({settings:{enabled:true,automatic:true,autoSide:true,time:100,darkMode:true}}));
  const fixture=await readFile('tests/fixture.html','utf8');
  await context.route('https://www.chess.com/**',route => route.fulfill({contentType:'text/html',body:fixture}));
  const page=await context.newPage();await page.goto('https://www.chess.com/play/computer');
  await page.locator('#gambaguette-arrow').waitFor({state:'visible'});
  const popup=await context.newPage();await popup.goto(`chrome-extension://${id}/popup.html`);
  const probe=await popup.evaluate(() => chrome.runtime.sendMessage({target:'overlay',action:'status',connect:true}));
  assert.equal(probe.ready,true,JSON.stringify(probe));
  await popup.locator('#private-overlay').click();
  await popup.waitForFunction(() => document.querySelector('#status').textContent.includes('Windows private overlay enabled'));
  const status=await popup.evaluate(() => chrome.runtime.sendMessage({target:'overlay',action:'status'}));
  assert.equal(status.ready,true,JSON.stringify(status));assert.equal(status.captureProtected,true);
  await page.bringToFront();
  await page.locator('#gambaguette').waitFor({state:'hidden'});
  await page.locator('#gambaguette-arrow').waitFor({state:'hidden'});
  assert.equal(await worker.evaluate(async () => (await chrome.storage.local.get('settings')).settings.privateOverlay),true);
  await page.screenshot({path:'test-results/private-browser-capture.png'});
  console.log(`PASS extension ${id}: registered Windows host, real handshake and DOM overlay exclusion`);
  assert.ok(Number.isInteger(status.process) && status.process > 0);
  process.kill(status.process);
  await page.waitForTimeout(300);
  assert.equal(await page.locator('#gambaguette').isVisible(),false);
  assert.equal(await page.locator('#gambaguette-arrow').isVisible(),false);
  console.log('PASS helper crash keeps the browser overlay hidden (no capture-leaking fallback)');
  await popup.bringToFront();await popup.locator('#private-overlay').uncheck();
  await page.bringToFront();await page.locator('#gambaguette').waitFor({state:'visible'});
  await page.locator('#gambaguette-arrow').waitFor({state:'visible'});
  console.log('PASS disabling private mode restores the themed browser overlay');
} finally {await context.close();}
